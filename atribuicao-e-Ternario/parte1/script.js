var numero = 10;

//Adição
numero+=10;     //numero =  numero + 10
console.log(numero);

//multiplicação
numero*=10;     //numero = numero *10
console.log(numero);

//subtração
numero-= 10;    //numero = numero - 10
console.log(numero);

//divisão
numero/=10;     //numero =numero / 10
console.log(numero);

//expoente
numero**=10;
console.log(numero); //numero =numero ^10

//módulo
numero %=10 //numero = numero %10
console.log(numero)



